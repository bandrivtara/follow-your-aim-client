export const buildLegacyDailyReviewSummary = (
  answers: Record<string, string> = {},
) =>
  DAILY_REVIEW_QUESTIONS.map((question) => {
    const answer = answers[question.id]?.trim();
    return answer ? `${question.title} ${answer}` : "";
  })
    .filter(Boolean)
    .join("\n");
